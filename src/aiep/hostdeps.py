"""Resolve host dependencies from declared requirements, not from a blind ``pip freeze``.

Starting from the direct requirements in ``requirements/host.in``, walk each
installed distribution's declared ``Requires-Dist`` (evaluating environment
markers and requested extras) and pin exactly the closure, at the installed
versions. Anything else in the environment (editable ``aiep`` itself, stray
tools) is left out. A required distribution that is not installed is an error,
never a guess.

Limits, recorded in the lock header: pins are ``==`` only (no artifact hashes can
be derived offline), and the lock is specific to the interpreter and platform it
was generated on.
"""

from __future__ import annotations

import platform
import sys
from importlib import metadata
from typing import Callable, Iterable

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

SELF = "aiep"


class ResolutionError(RuntimeError):
    pass


def parse_requirements(text: str) -> list[Requirement]:
    reqs = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            reqs.append(Requirement(line))
    return reqs


def _marker_ok(req: Requirement, extra: str) -> bool:
    return req.marker is None or req.marker.evaluate({"extra": extra})


def resolve(
    direct: Iterable[Requirement],
    get_dist: Callable[[str], "metadata.Distribution"] = metadata.distribution,
) -> dict[str, str]:
    """Return {canonical name: installed version} for the closure of ``direct``."""
    pinned: dict[str, str] = {}
    extras_done: dict[str, set[str]] = {}
    queue: list[tuple[str, frozenset[str], Requirement | None]] = [
        (canonicalize_name(r.name), frozenset(r.extras), r) for r in direct
    ]
    while queue:
        name, extras, via = queue.pop()
        try:
            dist = get_dist(name)
        except metadata.PackageNotFoundError:
            raise ResolutionError(f"required distribution {name!r} is not installed") from None
        version = dist.version
        if via is not None and via.specifier and not via.specifier.contains(version, prereleases=True):
            raise ResolutionError(f"{name}=={version} does not satisfy {via}")
        pinned[name] = version
        want = set(extras) | {""}
        seen = extras_done.setdefault(name, set())
        todo = want - seen
        if not todo:
            continue
        seen |= todo
        if extras:
            queue.append((name, frozenset(), None))  # base deps are always needed
        for text in dist.requires or []:
            child = Requirement(text)
            if any(_marker_ok(child, e) for e in todo):
                queue.append((canonicalize_name(child.name), frozenset(child.extras), child))
    pinned.pop(SELF, None)
    return dict(sorted(pinned.items()))


def render_lock(pinned: dict[str, str], direct_text: str) -> str:
    header = [
        "# GENERATED by scripts/lock_host_deps.py from requirements/host.in. Do not edit.",
        "# Host (harness-side) dependencies only; evaluator build dependencies are in config/wheelhouse.json.",
        f"# Generated on CPython {platform.python_version()} / {sys.platform} / {platform.machine()}; "
        "other platforms need their own lock.",
        "# Pins are exact versions of the installed closure. No artifact hashes: they cannot be derived offline.",
        "",
    ]
    return "\n".join(header + [f"{n}=={v}" for n, v in pinned.items()]) + "\n"
